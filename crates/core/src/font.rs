#[cfg(test)]
mod tests {
    use super::*;

    /// A character as rows of dots, for comparing with a drawing.
    fn drawn(c: char) -> Vec<String> {
        (0..HEIGHT)
            .map(|row| {
                (0..WIDTH)
                    .map(|column| if lit(c, column, row) { '#' } else { '.' })
                    .collect()
            })
            .collect()
    }

    #[test]
    fn letters_look_like_letters() {
        assert_eq!(
            drawn('A'),
            [".###.", "#...#", "#...#", "#...#", "#####", "#...#", "#...#"]
        );
        assert_eq!(
            drawn('T'),
            ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."]
        );
        assert_eq!(
            drawn('1'),
            ["..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###."]
        );
        assert!(drawn(' ').iter().all(|row| row == "....."));
        // Every printable character but the space has dots, and none is
        // drawn outside its seven rows.
        for code in 33u8..=126 {
            let columns = glyph(code as char);
            assert!(columns.iter().any(|c| *c != 0), "{} is blank", code as char);
            assert!(columns.iter().all(|c| c & 0x80 == 0), "{} is too tall", code as char);
        }
        // Anything else is a question mark.
        assert_eq!(glyph('é'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
        assert!(!lit('A', 9, 0) && !lit('A', 0, 9));
    }
}
