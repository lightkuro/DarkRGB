//! A 5 by 7 dot font for the printable ASCII characters, the classic one
//! used on small LED and LCD displays. Each character is five columns;
//! in each column the lowest bit is the top row.

/// Columns in a character.
pub const WIDTH: usize = 5;
/// Rows in a character.
pub const HEIGHT: usize = 7;

/// The columns of a character. Anything outside the printable ASCII
/// range is drawn as a question mark.
pub fn glyph(c: char) -> [u8; WIDTH] {
    let index = match c as u32 {
        code @ 32..=126 => (code - 32) as usize,
        _ => ('?' as u32 - 32) as usize,
    };
    GLYPHS[index]
}

/// Whether the dot at `column`, `row` of a character is lit.
pub fn lit(c: char, column: usize, row: usize) -> bool {
    column < WIDTH && row < HEIGHT && glyph(c)[column] >> row & 1 == 1
}

